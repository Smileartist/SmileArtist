/** Translate a key. Reads language from localStorage if lang not provided. */
export function t(key: string, lang?: string): string {
  const l = (lang || localStorage.getItem("app_language") || "english") as Lang;
  return translations[l]?.[key] ?? translations.english[key] ?? key;
}
